//! Port T.8 — fingerprint extraction.
//!
//! When a `PendingChange` is rejected, we extract a small feature
//! vector that captures the structural shape of the bad proposal.
//! Patterns are then learned across many fingerprints (see `pattern.rs`),
//! and at proposal time the pre-filter checks new candidates against
//! the learned-pattern set so Lu stops surfacing the same kinds of
//! low-quality bonds.
//!
//! The features here are heuristics, not exhaustive. Keep them small —
//! the user's empirical observation was that 8-10 features is the right
//! ceiling; more bits will overfit on noise.

use crate::bond::BondType;
use crate::pending::change::{PendingChange, PendingChangeKind};
use crate::source::SourceKind;
use serde::{Deserialize, Serialize};

/// Stable string-tag projection of `crate::source::SourceKind`. The
/// fingerprint stores the tag (not the full payload) so two `Research`
/// rejections with different `wonder_seed` payloads still group into
/// the same pattern bucket.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum SourceKindTag {
    TrainingCorpus,
    Research,
    Teach,
    Document,
    /// Port SourceKind-Variants — first-class chained-research tag.
    ChainedResearch,
    /// Port SourceKind-Variants — first-class session-promote tag.
    SessionPromote,
    /// Port SourceKind-Variants — first-class pack-install tag.
    PackInstall,
    Unknown,
}

impl SourceKindTag {
    pub fn from_kind(k: &SourceKind) -> Self {
        match k {
            SourceKind::TrainingCorpus { .. } => SourceKindTag::TrainingCorpus,
            SourceKind::Research { .. } => SourceKindTag::Research,
            SourceKind::Teach { .. } => SourceKindTag::Teach,
            SourceKind::Document { .. } => SourceKindTag::Document,
            SourceKind::ChainedResearch { .. } => SourceKindTag::ChainedResearch,
            SourceKind::SessionPromote { .. } => SourceKindTag::SessionPromote,
            SourceKind::PackInstall { .. } => SourceKindTag::PackInstall,
            SourceKind::Unknown => SourceKindTag::Unknown,
        }
    }

    pub fn as_str(&self) -> &'static str {
        match self {
            SourceKindTag::TrainingCorpus => "TrainingCorpus",
            SourceKindTag::Research => "Research",
            SourceKindTag::Teach => "Teach",
            SourceKindTag::Document => "Document",
            SourceKindTag::ChainedResearch => "ChainedResearch",
            SourceKindTag::SessionPromote => "SessionPromote",
            SourceKindTag::PackInstall => "PackInstall",
            SourceKindTag::Unknown => "Unknown",
        }
    }
}

/// Feature vector extracted from a rejected `PendingChange`. Only
/// `AddBond` changes are fingerprinted today — the other
/// `PendingChangeKind` variants either lack a subject/object/bond_type
/// triplet or aren't generated by the autonomous research path that
/// motivates this port.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct RejectionFingerprint {
    pub bond_type: BondType,
    /// Lowercased host of the proposal's `source_url` (e.g.
    /// `"grokipedia.com"`, `"en.wikipedia.org"`). Empty string when
    /// the proposal has no URL (manual teach, training corpus, etc.).
    pub source_domain: String,
    /// Categorical source class (Research / Teach / etc.).
    pub source_kind: SourceKindTag,
    /// `true` if the subject's first whitespace-token is in the
    /// preposition / function-word stoplist ("of", "in", "the", ...).
    pub subject_starts_with_preposition: bool,
    /// `true` if the subject contains a citation marker like `"5]"`
    /// or `"[12]"`. These are leftover artifacts from extraction
    /// passes over Wikipedia/Grokipedia HTML.
    pub subject_contains_citation_marker: bool,
    /// `true` if the subject contains a generic-pronoun token ("it",
    /// "this", "that", "they", ...). Pronoun-leading subjects almost
    /// always lack referent grounding.
    pub subject_contains_generic_pronoun: bool,
    pub subject_length_chars: u32,
    pub object_length_chars: u32,
    /// `true` if the object's last whitespace-token is in the
    /// preposition stoplist (object trails into a dependent clause
    /// that got truncated mid-sentence).
    pub object_ends_with_preposition: bool,
    pub confidence_at_rejection: f32,
    pub rejected_at_ms: u64,
}

impl RejectionFingerprint {
    /// Build a fingerprint from a `PendingChange` snapshot at the
    /// instant of rejection. Returns `None` when the change isn't a
    /// fingerprintable shape (currently only `AddBond` is
    /// fingerprinted; other `PendingChangeKind`s aren't generated by
    /// the autonomous research path so the rejection-pattern signal
    /// is moot for them).
    pub fn from_change(change: &PendingChange, rejected_at_ms: u64) -> Option<Self> {
        let (subject_text, object_text, bond_type) = match &change.change_kind {
            PendingChangeKind::AddBond {
                subject_text,
                object_text,
                bond_type,
                ..
            } => (subject_text.clone(), object_text.clone(), *bond_type),
            _ => return None,
        };
        let source_kind = SourceKindTag::from_kind(&change.proposed_by.kind);
        let url = match &change.proposed_by.kind {
            SourceKind::Research { url, .. } => url.clone(),
            _ => None,
        };
        let source_domain = extract_domain(url.as_deref());
        Some(RejectionFingerprint {
            bond_type,
            source_domain,
            source_kind,
            subject_starts_with_preposition: starts_with_preposition(&subject_text),
            subject_contains_citation_marker: contains_citation_marker(&subject_text),
            subject_contains_generic_pronoun: contains_generic_pronoun(&subject_text),
            subject_length_chars: subject_text.chars().count() as u32,
            object_length_chars: object_text.chars().count() as u32,
            object_ends_with_preposition: ends_with_preposition(&object_text),
            confidence_at_rejection: change.confidence,
            rejected_at_ms,
        })
    }
}

// =====================================================================
//                      Heuristic feature extractors
// =====================================================================

/// Function-words that, when they're the first or last token of a
/// subject/object string, almost always indicate a sentence-fragment
/// extraction rather than a clean concept name.
const PREPOSITIONS: &[&str] = &[
    "of", "in", "on", "at", "to", "for", "with", "from", "by",
    "into", "onto", "upon", "over", "under", "above", "below",
    "between", "through", "during", "before", "after", "since",
    "until", "about", "against", "among", "around", "as", "and",
    "or", "but", "the", "a", "an", "is", "was", "are", "were",
    "be", "been",
];

/// Generic referent-less pronouns. A subject that contains one of
/// these usually has lost its antecedent during extraction.
const GENERIC_PRONOUNS: &[&str] = &[
    "it", "this", "that", "these", "those", "they", "them", "we",
    "us", "i", "me", "you", "he", "she", "him", "her", "its",
    "their",
];

fn first_word(s: &str) -> Option<&str> {
    s.split_whitespace().next()
}

fn last_word(s: &str) -> Option<&str> {
    s.split_whitespace().last()
}

/// `true` if `s`'s first whitespace-delimited token is in PREPOSITIONS
/// (case-insensitive).
pub fn starts_with_preposition(s: &str) -> bool {
    let Some(w) = first_word(s) else { return false };
    let cleaned: String = w.chars().filter(|c| c.is_alphabetic()).collect();
    if cleaned.is_empty() {
        return false;
    }
    PREPOSITIONS.iter().any(|p| p.eq_ignore_ascii_case(&cleaned))
}

/// `true` if `s`'s last whitespace-delimited token is in PREPOSITIONS
/// (case-insensitive). Trailing punctuation is stripped before the
/// check.
pub fn ends_with_preposition(s: &str) -> bool {
    let Some(w) = last_word(s) else { return false };
    let cleaned: String = w.chars().filter(|c| c.is_alphabetic()).collect();
    if cleaned.is_empty() {
        return false;
    }
    PREPOSITIONS.iter().any(|p| p.eq_ignore_ascii_case(&cleaned))
}

/// `true` if `s` contains a citation-style marker:
///   * a digit immediately followed by `]`, e.g. `"5]"` or `"12]"`
///   * a `[NUM]` group, e.g. `"[1]"` or `"[42]"`.
///
/// These show up in subject/object text after extraction passes that
/// don't strip Wikipedia/Grokipedia footnote markers.
pub fn contains_citation_marker(s: &str) -> bool {
    let bytes = s.as_bytes();
    let n = bytes.len();
    let mut i = 0;
    while i < n {
        let b = bytes[i];
        // Pattern A: digit immediately before `]`.
        if b.is_ascii_digit() && i + 1 < n && bytes[i + 1] == b']' {
            return true;
        }
        // Pattern B: `[NUM]`.
        if b == b'[' {
            let mut j = i + 1;
            let mut saw_digit = false;
            while j < n && bytes[j].is_ascii_digit() {
                saw_digit = true;
                j += 1;
            }
            if saw_digit && j < n && bytes[j] == b']' {
                return true;
            }
        }
        i += 1;
    }
    false
}

/// `true` if any whitespace-delimited token of `s` (lowercased,
/// alphabetic-only) is in `GENERIC_PRONOUNS`.
pub fn contains_generic_pronoun(s: &str) -> bool {
    for tok in s.split(|c: char| !c.is_alphabetic()) {
        if tok.is_empty() {
            continue;
        }
        let lower = tok.to_ascii_lowercase();
        if GENERIC_PRONOUNS.iter().any(|p| *p == lower.as_str()) {
            return true;
        }
    }
    false
}

/// Extract the lowercased host of a URL. Returns `""` for `None`.
/// Does not depend on the `url` crate — string-shaped extraction
/// suffices because we only use the result as a grouping key.
pub fn extract_domain(url: Option<&str>) -> String {
    let Some(u) = url else { return String::new() };
    let after_scheme = u.split_once("://").map(|(_, r)| r).unwrap_or(u);
    let host = after_scheme
        .split(|c: char| c == '/' || c == '?' || c == '#')
        .next()
        .unwrap_or("");
    host.to_ascii_lowercase()
}
